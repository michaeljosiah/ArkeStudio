import assert from "node:assert/strict";
import { it } from "node:test";
import { act } from "react";
import { createRoot } from "react-dom/client";
import { parseHTML } from "linkedom";
import { type ClientMessage, type ManifestModel, compileAudiobookPerformance } from "@arke-studio/contracts";
import { CharacterNarration } from "../src/components/character-narration.js";
import { __connectionStatusForTest, __setBridgeForTest, __setStateForTest } from "../src/lib/store.js";
import { FIXTURE_STATE } from "./fixture-state.js";

const dom = parseHTML("<!doctype html><html><body></body></html>");
Object.assign(globalThis, { window: dom.window, document: dom.document, HTMLElement: dom.HTMLElement, Node: dom.Node, Event: dom.Event, IS_REACT_ACT_ENVIRONMENT: true });
const model: ManifestModel = { id: "eleven_v4", provider: "elevenlabs", capability: "voice-tts", displayName: "Eleven v4", accepts: { referenceImages: 0, startFrame: false, endFrame: false }, limits: { maxPromptChars: 10000, audioFormat: "wav" }, pricing: { kind: "perCharacter", microUsdPerCharacter: 80 }, cadence: { deliveries: ["measured"], speed: null, pause: "best-effort-audio-tag", breath: "best-effort-audio-tag", emphasis: "best-effort-capitalization", outputTimestamps: "none", phrase: "best-effort-tag", tagChars: 160, deliveryMappings: {} } };
const props = (element: Element) => (element as unknown as Record<string, { onChange(e: { target: { value: string } }): void; onBlur(e?: { relatedTarget: EventTarget | null }): void }>)[Object.keys(element).find(k => k.startsWith("__reactProps$"))!]!;

it("book edits default to the character; overrides are deliberate, visible, and removable without generating audio", async t => {
  let state = structuredClone(FIXTURE_STATE);
  const world = state.world!;
  const sheet = world.sheets.find(s => s.type === "character")!;
  sheet.narration = "calm American delivery";
  const book = world.productions[0]!;
  book.audiobook = { schemaVersion: 1, reading: "performed", narrator: { provider: "elevenlabs", model: model.id, voiceId: "Calen", label: "Calen" } };
  state.app.manifest = { ...state.app.manifest!, models: [model] };
  const sent: ClientMessage[] = [];
  __setBridgeForTest({ appVersion: "test", platform: "test", connect() {}, subscribe() {}, send(raw: string) { sent.push(JSON.parse(raw)); } });
  __setStateForTest(state); __connectionStatusForTest("open");
  const host = document.createElement("div"); document.body.append(host);
  const root = createRoot(host);
  t.after(async () => { await act(async () => root.unmount()); host.remove(); __setBridgeForTest(null); __setStateForTest(FIXTURE_STATE); });
  await act(async () => root.render(<CharacterNarration worldId={world.meta.worldId} productionId={book.meta.id} speakerKey={sheet.id} name={sheet.name} />));
  const field = (prefix: string) => host.querySelector(`textarea[aria-label="${prefix} · ${sheet.name}"]`)!;
  const effective = () => host.querySelector('[data-testid="narration-effective"] code')!.textContent;
  const toggle = () => host.querySelector('[data-testid="narration-override-toggle"]') as HTMLButtonElement;
  assert.equal(effective(), "[calm American delivery]");
  assert.equal(field("Book override"), null);
  await act(async () => props(field("Narration")).onChange({ target: { value: "quiet American delivery" } }));
  await act(async () => props(field("Narration")).onBlur());
  assert.deepEqual(sent.at(-1), { kind: "set-sheet-narration", worldId: world.meta.worldId, path: `characters/${sheet.id}.md`, narration: "quiet American delivery" });
  assert.equal(sent.some(m => m.kind === "set-audiobook-note"), false);
  const beforeOpening = sent.length;
  await act(async () => toggle().click());
  assert.ok(field("Book override"));
  assert.equal(sent.length, beforeOpening, "opening an override neither saves nor generates");
  await act(async () => props(field("Book override")).onChange({ target: { value: "unsaved override" } }));
  await act(async () => props(field("Book override")).onBlur({ relatedTarget: toggle() }));
  await act(async () => toggle().click());
  assert.equal(sent.length, beforeOpening, "cancelling an uncommitted override does not write it");
  await act(async () => toggle().click());
  assert.equal((field("Book override") as HTMLTextAreaElement).value, "");
  await act(async () => props(field("Book override")).onChange({ target: { value: "calm clipped British delivery" } }));
  await act(async () => props(field("Book override")).onBlur({ relatedTarget: null }));
  assert.equal(sent.at(-1)?.kind, "set-audiobook-note");
  state = structuredClone(state);
  state.world!.productions[0]!.audiobook!.notes = { [sheet.id]: "calm clipped British delivery" };
  await act(async () => __setStateForTest(state));
  assert.equal(effective(), "[calm clipped British delivery]");
  assert.match(host.textContent!, /Overrides Character narration/);
  assert.equal((field("Narration") as HTMLTextAreaElement).value, "calm American delivery", "override does not replace the character editor");
  await act(async () => toggle().click());
  assert.deepEqual(sent.at(-1), { kind: "set-audiobook-note", worldId: world.meta.worldId, productionId: book.meta.id, speaker: sheet.id, note: null });
  delete state.world!.productions[0]!.audiobook!.notes;
  await act(async () => __setStateForTest(structuredClone(state)));
  assert.equal(effective(), "[calm American delivery]");
  assert.equal(sent.some(m => m.kind === "read-audiobook-chapter" || m.kind === "voice-preview" || m.kind === "hear-audiobook-line"), false);
  await act(async () => __connectionStatusForTest("closed"));
  assert.equal((field("Narration") as HTMLTextAreaElement).disabled, true);
  assert.equal(toggle().disabled, true);
});

it("effective preview matches v4 compilation for legacy briefs, held notes, reading modes and unnamed speakers", async t => {
  const state = structuredClone(FIXTURE_STATE);
  const world = state.world!; const book = world.productions[0]!;
  const brief = "male narrator imitating a British woman, slight pitch lift, retain male timbre";
  book.audiobook = { schemaVersion: 1, reading: "performed", notes: { Doctor: brief }, narrator: { provider: "elevenlabs", model: model.id, voiceId: "Calen" } };
  state.app.manifest = { ...state.app.manifest!, models: [model] };
  __setStateForTest(state); __connectionStatusForTest("open");
  const host = document.createElement("div"); document.body.append(host); const root = createRoot(host);
  t.after(async () => { await act(async () => root.unmount()); host.remove(); __setStateForTest(FIXTURE_STATE); });
  await act(async () => root.render(<CharacterNarration worldId={world.meta.worldId} productionId={book.meta.id} speakerKey="Doctor" name="Doctor" />));
  const cue = () => host.querySelector('[data-testid="narration-effective"] code')!.textContent!;
  assert.equal(host.querySelector('textarea[aria-label="Narration · Doctor"]'), null);
  assert.match(host.textContent!, /speaker has no character sheet/);
  assert.equal(cue(), "[slight pitch lift, British delivery]");
  const compiled = compileAudiobookPerformance({ key: "p0.0", paragraph: 0, text: "Hello.", speaker: "Doctor" }, book.audiobook, null, model)!;
  assert.equal(compiled.text, `${cue()} Hello.`);
  book.audiobook.notes = { Doctor: "x".repeat(161) };
  await act(async () => __setStateForTest(structuredClone(state)));
  assert.match(cue(), /^Not sent/);
  await act(async () => __setStateForTest(structuredClone(state), { voiceCatalogueHeld: [] }));
  assert.match(host.textContent!, /kokoro-82m/, "unavailable saved voice resolves to shipped narrator");
  assert.doesNotMatch(cue(), /slight pitch lift/, "does not claim the unavailable v4 cue will be sent");
  book.audiobook.reading = "narrator";
  await act(async () => __setStateForTest(structuredClone(state)));
  assert.equal(cue(), "Not sent in this reading mode");
});
