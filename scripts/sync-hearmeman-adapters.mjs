import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Inventory intake only: no weight downloads, installation, activation or policy changes.
const repository = "Hearmeman/minimax-h3-loras";
const target = fileURLToPath(new URL("../packages/providers/src/comfyui/hearmeman.generated.ts", import.meta.url));
const args = process.argv.slice(2);
const revision = args.find(arg => arg.startsWith("--revision="))?.slice(11) ?? "de4c3bc6122e68b88407c03dfecf521c803f098d";
if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error("Supply an immutable 40-character revision.");
for (const arg of args) if (arg !== "--write" && arg !== "--check" && !arg.startsWith("--revision=")) throw new Error(`Unknown option: ${arg}`);
const old = await readFile(target, "utf8").catch(error => { if (error.code === "ENOENT") return ""; throw error; });
const previous = old ? JSON.parse(old.match(/export const HEARMEMAN_ADAPTERS = ([\s\S]+)\.map\(row => AdapterReleaseSchema.parse\(row\)\);/)?.[1] ?? "null") : [];
if (!Array.isArray(previous)) throw new Error("Cannot read the previous inventory; keep it intact and repair its format first.");
const checkedAt = previous.find(row => row.source.revision === revision)?.assessedAt ?? new Date().toISOString();
let url = `https://huggingface.co/api/models/${repository}/tree/${revision}?recursive=true&expand=false`;
const files = [];
const visited = new Set();
while (url) {
  if (visited.has(url) || new URL(url).origin !== "https://huggingface.co") throw new Error("Unexpected inventory pagination.");
  visited.add(url);
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`Inventory request failed (${response.status}).`);
  const page = await response.json();
  if (!Array.isArray(page)) throw new Error("Invalid inventory response.");
  files.push(...page.filter(row => row.path?.endsWith(".safetensors")));
  url = response.headers.get("link")?.match(/<([^>]+)>;\s*rel="next"/)?.[1] ?? "";
}
const releaseId = file => `hearmeman-${file.path.replace(/\.safetensors$/, "").toLowerCase().replaceAll("_", "-")}-${file.lfs.oid}`;
const families = {
  "HMBreastsV2.safetensors": "hearmeman-hmbreasts", "HMBreasts_085e0750_e40.safetensors": "hearmeman-hmbreasts",
  "HMCumshot_V1.0.safetensors": "hearmeman-hmcumshot", "HMCumshot_V2.safetensors": "hearmeman-hmcumshot",
  "HMNSFW-AIO-V2.5.safetensors": "hearmeman-hmnsfw-aio", "HMNSFW_AIO_V2.safetensors": "hearmeman-hmnsfw-aio",
};
// Only explicit named publisher versions are related; similar anatomy labels are not
// evidence of a common model family. Old releases remain inspectable, never auto-replaced.
const priorVersions = {
  "HMBreastsV2.safetensors": "HMBreasts_085e0750_e40.safetensors",
  "HMCumshot_V2.safetensors": "HMCumshot_V1.0.safetensors",
  "HMNSFW-AIO-V2.5.safetensors": "HMNSFW_AIO_V2.safetensors",
};
const entries = files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0).map(file => {
  if (!/^[\w.-]+\.safetensors$/.test(file.path) || !/^[a-f0-9]{64}$/.test(file.lfs?.oid) || !Number.isSafeInteger(file.size) || file.size <= 0) throw new Error(`Unverified artifact metadata: ${file.path}`);
  const id = releaseId(file);
  const existing = previous.find(row => row.id === id);
  if (existing) return { ...existing, availability: "current" };
  const superseded = files.find(row => row.path === priorVersions[file.path]);
  return {
    id, adapterId: families[file.path] ?? id.slice(0, -65), publisher: "Hearmeman", displayName: file.path.replace(/\.safetensors$/, ""),
    source: { repository, revision, file: file.path, bytes: file.size, sha256: file.lfs.oid },
    license: { name: "minimax-h3-community-license", url: `https://huggingface.co/${repository}/blob/${revision}/README.md` },
    classification: "adult", baseFamily: "minimax-h3", availability: "current", supersedes: superseded ? [releaseId(superseded)] : [], assessedAt: checkedAt,
    compatibility: ["comfyui-h3-video", "comfyui-h3-video-768", "comfyui-h3-reference-video"].map(recipeId => ({
      recipeId, state: "unverified", reason: "Adapter and recipe pairing has not completed Arke GPU validation.",
    })),
  };
});
// Preserve immutable old releases and evidence when upstream deletes or replaces a file.
for (const row of previous) if (row.id.endsWith(row.source.sha256) && !entries.some(next => next.id === row.id)) entries.push({ ...row, availability: "withdrawn" });
if (new Set(entries.map(row => row.id)).size !== entries.length || !entries.length) throw new Error("Empty inventory or colliding release identities.");
const output = `// Generated by scripts/sync-hearmeman-adapters.mjs. Review source changes before activation.\nimport { AdapterReleaseSchema } from "@arke-studio/contracts";\n\nexport const HEARMEMAN_ADAPTERS = ${JSON.stringify(entries, null, 2)}.map(row => AdapterReleaseSchema.parse(row));\n`;
console.log(`${entries.length} artifacts, ${entries.reduce((total, row) => total + row.source.bytes, 0)} bytes, revision ${revision}`);
console.log(`Current: ${entries.filter(row => row.availability === "current").length}; withdrawn: ${entries.filter(row => row.availability === "withdrawn").length}; new: ${entries.filter(row => !previous.some(prior => prior.id === row.id)).length}`);
if (old === output) console.log("Inventory is unchanged.");
else if (args.includes("--write")) { await writeFile(target, output); console.log("Wrote the inventory for review; nothing installed or enabled."); }
else { console.log("Inventory differs. Inspect the source and use --write to stage the update."); if (args.includes("--check")) process.exitCode = 1; }
