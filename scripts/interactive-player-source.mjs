// The players' text, for the exporters (design turns 156 and 186).
//
//   node scripts/interactive-player-source.mjs           write the copies
//   node scripts/interactive-player-source.mjs --check   fail if one has drifted (lint runs this)
//
// packages/contracts/src/interactive-player.js and audiobook-player.js are the two players: the app
// imports each and mounts it over the window, and every exported package carries its player inline
// in player.html. The exporter cannot read the file at run time — the desktop build bundles the
// coordinator into one file, and a function's own source is not stable across tsx and esbuild — so
// it reads a copy, a string constant written from the file. The check keeps each pair identical,
// so the player an author previews and the package a viewer opens can never be two players.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "contracts", "src");
const players = [
  { module: "interactive-player.js", target: "interactive-player-source.ts", name: "INTERACTIVE_PLAYER_SOURCE", turn: "156", what: "interactive player" },
  { module: "audiobook-player.js", target: "audiobook-player-source.ts", name: "AUDIOBOOK_PLAYER_SOURCE", turn: "186", what: "audiobook player" },
];

let drifted = false;
for (const player of players) {
  const text = readFileSync(join(src, player.module), "utf8").replace(/\r\n/g, "\n");
  const target = join(src, player.target);
  const copy = `// Generated by scripts/interactive-player-source.mjs from ${player.module} — do not edit.
// The exporter inlines this into player.html; the app imports the module itself (design turn ${player.turn}).
export const ${player.name} = ${JSON.stringify(text)};
`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // Reported below as drift.
    }
    if (current !== copy) {
      console.error(`${player.what}: ${player.target} is behind ${player.module} — run \`node scripts/interactive-player-source.mjs\` and commit it`);
      drifted = true;
    } else console.log(`${player.what}: the exporter's copy matches the module`);
  } else {
    writeFileSync(target, copy);
    console.log(`${player.what}: wrote ${target}`);
  }
}
if (drifted) process.exit(1);
