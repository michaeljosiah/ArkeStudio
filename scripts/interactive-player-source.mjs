// The interactive player's text, for the exporter (design turn 156).
//
//   node scripts/interactive-player-source.mjs           write the copy
//   node scripts/interactive-player-source.mjs --check   fail if it has drifted (lint runs this)
//
// packages/contracts/src/interactive-player.js is the one player: the app imports it and mounts
// it over the window, and every exported package carries it inline in player.html. The exporter
// cannot read the file at run time — the desktop build bundles the coordinator into one file, and
// a function's own source is not stable across tsx and esbuild — so it reads this copy, a string
// constant written from the file. The check keeps the two identical, so the preview an author
// walks and the package a viewer opens can never be two different players.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "contracts", "src");
const player = readFileSync(join(src, "interactive-player.js"), "utf8").replace(/\r\n/g, "\n");
const target = join(src, "interactive-player-source.ts");
const text = `// Generated by scripts/interactive-player-source.mjs from interactive-player.js — do not edit.
// The exporter inlines this into player.html; the app imports the module itself (design turn 156).
export const INTERACTIVE_PLAYER_SOURCE = ${JSON.stringify(player)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // Reported below as drift.
  }
  if (current !== text) {
    console.error("interactive player: interactive-player-source.ts is behind interactive-player.js — run `node scripts/interactive-player-source.mjs` and commit it");
    process.exit(1);
  }
  console.log("interactive player: the exporter's copy matches the module");
} else {
  writeFileSync(target, text);
  console.log(`interactive player: wrote ${target}`);
}
